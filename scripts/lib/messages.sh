# ─── Language helpers ────────────────────────────────────────────────────────

# t KEY [ARG1 ARG2 ...] — translate (with printf-style substitution)
t() {
    local key="$1"; shift || true
    local fmt
    # ${arr[k]+x} tests whether the key EXISTS; ${arr[k]:-d} would treat a
    # deliberately empty string as missing and fall through — which in the
    # Python port made an intentionally blank table header render as the
    # literal key name on every page.
    if [[ "$LANG_CHOICE" == "de" && -n "${MSG_DE[$key]+x}" ]]; then
        fmt="${MSG_DE[$key]}"
    elif [[ -n "${MSG_EN[$key]+x}" ]]; then
        fmt="${MSG_EN[$key]}"
    else
        fmt="MISSING:$key"
    fi
    # A double hyphen before the format, because a message may legitimately
    # begin with one and printf would then read it as its own option. Found on
    # a real run: the restore's "--dry-run: every check runs…" line printed
    # "printf: --: invalid option" and then a blank warning, which is the worst
    # shape a bug can take — the operator sees an empty warning in the middle
    # of a restore and cannot tell what was not said.
    #
    # No backticks anywhere in this file, comments included; the check that
    # enforces that reads the whole file, and narrowing it to accommodate a
    # comment would be the wrong trade.
    # shellcheck disable=SC2059
    printf -- "$fmt" "$@"
}

# auto-detect language from $LANG env var
detect_default_language() {
    if [[ "${LANG:-}" == de* ]]; then
        echo "de"
    else
        echo "en"
    fi
}

# Interactive language selection
select_language() {
    # already set by --lang flag?
    if [[ -n "$LANG_CHOICE" ]]; then return 0; fi

    local default; default="$(detect_default_language)"
    local default_num
    if [[ "$default" == "de" ]]; then default_num=2; else default_num=1; fi

    printf "${BOLD}%s${RESET}\n" "$(t lang_prompt)"
    printf "    ${BOLD}[1]${RESET}  %s\n" "$(t lang_en)"
    printf "    ${BOLD}[2]${RESET}  %s\n" "$(t lang_de)"
    printf "  ${DIM}%s${RESET} ${BOLD}[%d]${RESET}: " "$(t enter_choice)" "$default_num"

    local input
    IFS= read -r input
    input="${input:-$default_num}"
    case "$input" in
        2) LANG_CHOICE="de" ;;
        *) LANG_CHOICE="en" ;;
    esac
    export LANG_CHOICE
}

# Lint: report any DE keys missing from MSG_EN, or vice versa
check_translations() {
    local key missing_de=() missing_en=()
    for key in "${!MSG_EN[@]}"; do
        [[ -z "${MSG_DE[$key]:-}" ]] && missing_de+=("$key")
    done
    for key in "${!MSG_DE[@]}"; do
        [[ -z "${MSG_EN[$key]:-}" ]] && missing_en+=("$key")
    done
    if (( ${#missing_de[@]} > 0 )); then
        warn "Missing German translations: ${missing_de[*]}"
    fi
    if (( ${#missing_en[@]} > 0 )); then
        warn "Missing English translations: ${missing_en[*]}"
    fi
    return 0
}
